-- ================================================
-- ファイル名: 23_select_gap_ranges.sql
-- 役割:
--   Numbers テーブルから、欠番のかたまりを区間として表示する。
--
-- このSQLの目的:
--   実在する各数に対して
--     その次に来る実在値
--   を求め、
--   その間に空白があれば
--     gap_start ～ gap_end
--   の形で欠番区間を返すこと。
--
-- 学習上の主題:
--   - 自己結合による「次に大きい値」の探索
--   - MIN() を使った最近接の上側境界の取得
--   - GROUP BY / HAVING による欠番区間の抽出
--   - 欠番を「個々の値」ではなく「連続区間」として返す考え方
--
-- 今回の最重要ポイント:
--   このSQLでは、
--   各数 N1.num に対して
--     N1.num より大きい数 N2.num
--   を全部集め、
--   その中で最小のもの
--     MIN(N2.num)
--   を取っている。
--
--   これは
--     「N1.num の直後に現れる実在値」
--   を意味する。
--
--   もし
--     N1.num + 1 < MIN(N2.num)
--   なら、
--   その間には少なくとも1つ以上の欠番がある。
--
--   そして
--     欠番開始 = N1.num + 1
--     欠番終了 = MIN(N2.num) - 1
--   で求まる。
--
--   つまりアルゴリズムとしては
--     1. 各数について、自分より大きい数を集める
--     2. その最小値を「次の実在値」とみなす
--     3. 直後の数と次の実在値の間に隙間があるか判定する
--     4. 隙間があれば欠番区間として返す
--   という流れになっている。
--
--   これがこのSQLの本質である。
-- ================================================

SELECT
       (N1.num + 1) AS gap_start,
       -- gap_start:
       --   欠番区間の開始値である。
       --
       --   現在見ている実在値 N1.num の
       --   「次の整数」
       --   から欠番が始まる。
       --
       --   たとえば N1.num = 4 なら、
       --   その直後の整数は 5 なので
       --   欠番開始候補は 5 になる。
       --
       --   もちろん実際に欠番があるかどうかは
       --   HAVING 句で判定する。

       '～',
       -- 区切り文字:
       --   始点と終点の間を見やすく表示するための文字列である。
       --
       --   SQL 的な意味は特に無く、
       --   結果表示を「区間」に見せるための補助である。

       (MIN(N2.num) - 1) AS gap_end
       -- gap_end:
       --   欠番区間の終了値である。
       --
       --   MIN(N2.num) は
       --     N1.num より大きい実在値のうち最小のもの
       --   である。
       --
       --   つまり
       --     N1.num の直後に現れる実在値
       --   を表す。
       --
       --   欠番はその直前まで続くので、
       --     gap_end = MIN(N2.num) - 1
       --   になる。
       --
       --   たとえば N1.num = 4 のとき、
       --   自分より大きい値は
       --     7,8,9,12
       --   であり、その最小は 7 である。
       --
       --   したがって
       --     gap_end = 7 - 1 = 6
       --   となり、
       --   欠番区間は 5～6 だと分かる。

  FROM Numbers N1
       INNER JOIN Numbers N2
         ON N2.num > N1.num
         -- 自己結合:
         --   同じ Numbers 表を
         --     N1 = 現在値側
         --     N2 = それより大きい値側
         --   として2回使っている。
         --
         -- N2.num > N1.num:
         --   N1 より大きい数だけを N2 として結び付ける。
         --
         --   たとえば N1.num = 4 のとき、
         --   結び付く N2.num は
         --     7,8,9,12
         --   になる。
         --
         --   ここで重要なのは、
         --   「直後の値」だけを直接結び付けているわけではなく、
         --   自分より大きい値を全部集めていること。
         --
         --   その後 MIN(N2.num) を取ることで、
         --   その中から
         --     最も近い上側の値
         --   を取り出している。
         --
         --   つまりこの自己結合は
         --     「候補となる上側の実在値を全部集める」
         --   段階である。

 GROUP BY N1.num
 -- GROUP BY N1.num:
 --   現在値 N1.num ごとに1グループを作る。
 --
 --   これにより各 N1 について
 --     自分より大きい N2 の集合
 --   をまとめて扱える。
 --
 --   そのグループに対して
 --     MIN(N2.num)
 --   を取ることで、
 --   その N1 の「次の実在値」を求めている。
 --
 --   つまり GROUP BY は
 --     各現在値ごとに上側候補群を整理する
 --   役割を持つ。

HAVING
       (N1.num + 1) < MIN(N2.num);
       -- HAVING 条件:
       --   ここが「本当に欠番があるか」を判定する条件である。
       --
       -- 左辺:
       --   N1.num + 1
       --   -> N1 の直後の整数
       --
       -- 右辺:
       --   MIN(N2.num)
       --   -> 次に現れる実在値
       --
       -- もし
       --   N1.num + 1 = MIN(N2.num)
       -- なら、
       --   直後の整数がそのまま次の実在値であり、
       --   その間に欠番は無い。
       --
       --   例:
       --     3 の次が 4
       --   なら欠番無し。
       --
       -- 一方
       --   N1.num + 1 < MIN(N2.num)
       -- なら、
       --   直後の整数から次の実在値までの間に
       --   1つ以上の欠番が存在する。
       --
       --   例:
       --     4 の次の実在値が 7
       --   なら
       --     5,6
       --   が欠番である。
       --
       --   したがってこの HAVING により、
       --   欠番のかたまりが存在する N1 だけを残している。


-- ================================================
-- このSQLの処理の流れ
-- ================================================
--
-- 1. Numbers の各値 N1 を現在値候補とする
-- 2. それより大きい Numbers の値 N2 を全部結び付ける
-- 3. N1 ごとに MIN(N2.num) を取り、次の実在値を求める
-- 4. N1.num + 1 と比較し、間に空白があるか判定する
-- 5. 空白があれば
--      gap_start = N1.num + 1
--      gap_end   = MIN(N2.num) - 1
--    を返す
--
-- 概念的には次のような処理に近い。
--
--   for each existing number x in Numbers:
--       next_existing = minimum y in Numbers where y > x
--
--       if x + 1 < next_existing:
--           output (x + 1) ~ (next_existing - 1)
--
-- つまりこれは、
--   「各実在値について、次の実在値までの隙間を調べる」
--   アルゴリズムである。


-- ================================================
-- 実データでのイメージ
-- ================================================
--
-- Numbers の値:
--   1
--   3
--   4
--   7
--   8
--   9
--   12
--
-- N1 ごとに次の実在値 MIN(N2.num) を見る。
--
-- N1 = 1:
--   自分より大きい値は
--     3,4,7,8,9,12
--   最小は 3
--
--   1 + 1 = 2
--   2 < 3 なので欠番あり
--   gap = 2 ～ 2
--
-- N1 = 3:
--   自分より大きい値の最小は 4
--   3 + 1 = 4
--   4 < 4 は偽
--   -> 欠番なし
--
-- N1 = 4:
--   自分より大きい値の最小は 7
--   4 + 1 = 5
--   5 < 7 は真
--   -> gap = 5 ～ 6
--
-- N1 = 7:
--   次の実在値は 8
--   8 < 8 は偽
--   -> 欠番なし
--
-- N1 = 8:
--   次の実在値は 9
--   9 < 9 は偽
--   -> 欠番なし
--
-- N1 = 9:
--   次の実在値は 12
--   10 < 12 は真
--   -> gap = 10 ～ 11
--
-- よって最終結果は概ね
--
--   2   ～   2
--   5   ～   6
--   10  ～   11
--
-- になる。


-- ================================================
-- 図解: 次の実在値との隙間を見る
-- ================================================
--
--   実在値:
--   1   3 4   7 8 9   12
--   |   | |   | | |    |
--   |   | |   | | |    +-- 次の実在値なし
--   |   | |   | | +------- gap 10～11
--   |   | |   | +--------- gap なし
--   |   | |   +----------- gap なし
--   |   | +--------------- gap 5～6
--   |   +----------------- gap なし
--   +--------------------- gap 2～2
--
-- つまり、
--   各実在値から見て「次の実在値」がどこかを求め、
--   その間の空白を区間として返している。


-- ================================================
-- このSQLの本質
-- ================================================
--
-- このSQLの本質は、
--   欠番を「存在しない個々の値」として直接探すのではなく、
--   実在する値どうしの間の空白区間として捉えている
-- ところにある。
--
-- つまり
--   欠番 2
--   欠番 5
--   欠番 6
--   欠番 10
--   欠番 11
-- を1個ずつ列挙するのではなく、
--
--   2 ～ 2
--   5 ～ 6
--   10 ～ 11
--
-- という「かたまり」で返す。
--
-- そのためには、
--   各値の次に来る実在値
-- を知ることが重要になる。
--
-- これを
--   自己結合 + MIN()
-- で実現している。
--
-- これがこのSQLの核心である。


-- ================================================
-- 構文ごとの意味
-- ================================================
--
-- Numbers N1
--   → 現在見ている実在値
--
-- Numbers N2
--   → N1 より大きい上側候補の実在値
--
-- ON N2.num > N1.num
--   → N1 より大きい値だけ集める
--
-- GROUP BY N1.num
--   → 各現在値ごとに上側候補群をまとめる
--
-- MIN(N2.num)
--   → 次に現れる実在値を求める
--
-- HAVING (N1.num + 1) < MIN(N2.num)
--   → その間に少なくとも1つ以上の欠番があるか判定する
--
-- (N1.num + 1) AS gap_start
--   → 欠番区間の開始
--
-- (MIN(N2.num) - 1) AS gap_end
--   → 欠番区間の終了
-- ================================================