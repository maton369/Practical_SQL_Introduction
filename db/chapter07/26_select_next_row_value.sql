-- ================================================
-- ファイル名: 26_select_next_row_value.sql
-- 役割:
--   Numbers テーブルの各行に対して、
--   「次の1行の num」を取得する。
--
-- このSQLの目的:
--   欠番区間を求める前段階として、
--   各実在値の直後に来る実在値を
--   ウィンドウ関数で取り出せることを確認すること。
--
-- 学習上の主題:
--   - ウィンドウ関数で「次の1行」を参照する方法
--   - ORDER BY num に基づく隣接行の考え方
--   - ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING の意味
--   - リスト8.17の diff 計算の中身
--
-- 今回の最重要ポイント:
--   このSQLは、
--   各 num に対して
--     「ソート順で直後にある num」
--   を next_num として持たせている。
--
--   つまりアルゴリズムとしては
--     1. Numbers を num 昇順に並べる
--     2. 各行について次の1行だけを見る
--     3. その値を next_num として返す
--   という「隣接行参照」そのものである。
--
--   リスト8.17では
--     diff = next_num - num
--   を使って欠番区間を求めた。
--
--   今回のSQLは、その元になっている
--   next_num 取得処理だけを取り出したものである。
-- ================================================

SELECT
       num,
       -- num:
       --   現在見ている実在値である。
       --
       --   この行を基準にして、
       --   直後の実在値 next_num を求める。
       --
       --   たとえば num=4 なら、
       --   次の行は 7 なので
       --   next_num は 7 になる。

       MAX(num) OVER (
           ORDER BY num
           ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING
       ) AS next_num
       -- MAX(num) OVER (...):
       --   ウィンドウ関数を使って、
       --   現在行の「1行あと」にある num を取り出している。
       --
       -- ORDER BY num:
       --   num 昇順で行の並び順を定めている。
       --
       --   したがって、
       --   このSQLでいう「次の1行」とは
       --   num が1つ大きいとは限らず、
       --   あくまで
       --     ソート順で次に存在する行
       --   を意味する。
       --
       --   たとえばデータが
       --     1,3,4,7,8,9,12
       --   なら、
       --     4 の次の1行は 7
       --   である。
       --
       -- ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING:
       --   ここが最重要ポイントである。
       --
       --   これは
       --     「現在行の1行あとから1行あとまで」
       --   という意味であり、
       --   ウィンドウフレームを
       --     ちょうど次の1行だけ
       --   に限定している。
       --
       --   つまりこのフレームの中には
       --   1つの値しか入らない。
       --
       -- MAX(num) を使っている理由:
       --   フレームが1行だけなので、
       --   MAX(num) を取っても
       --   その1値自身が返る。
       --
       --   そのため、実質的には
       --     「次の1行の num を返す」
       --   のと同じ意味になる。
       --
       -- next_num:
       --   現在行の次に現れる実在値を表す。
       --
       --   たとえば
       --     num = 1 なら next_num = 3
       --     num = 3 なら next_num = 4
       --     num = 4 なら next_num = 7
       --   となる。
       --
       -- 最後の行について:
       --   最後の num=12 のように
       --   次の行が存在しない場合は、
       --   参照できる1行あとが無いので
       --   next_num は NULL になる。
       --
       --   これも非常に重要である。
       --
       --   つまりこのSQLは
       --     次の行が存在する限りその値を返し、
       --     存在しないなら NULL を返す
       --   隣接参照になっている。

  FROM Numbers;
  -- FROM Numbers:
  --   元表である。
  --
  --   ここでは Numbers の各行に対して
  --     その次の1行の値
  --   を付加した結果を返している。
  --
  --   つまり元表の各行に
  --     「次の実在値」
  --   という補助情報を追加している。


-- ================================================
-- このSQLの処理の流れ
-- ================================================
--
-- 1. Numbers を num 昇順に並べる
-- 2. 各行について次の1行だけを見る
-- 3. その num を next_num として返す
--
-- 概念的には次のような処理に近い。
--
--   sort nums ascending
--
--   for each row i:
--       next_num = value at row i+1
--       output current_num, next_num
--
-- つまりこれは、
--   「ソート済み列に対して、隣の要素を取り出す」
--   アルゴリズムである。


-- ================================================
-- 実データでのイメージ
-- ================================================
--
-- Numbers:
--   1
--   3
--   4
--   7
--   8
--   9
--   12
--
-- これに対して next_num を付けると、
--
--   1   -> 3
--   3   -> 4
--   4   -> 7
--   7   -> 8
--   8   -> 9
--   9   -> 12
--   12  -> NULL
--
-- となる。
--
-- これがリスト8.17で使っていた
--   次の実在値
-- そのものである。
--
-- ここから
--   diff = next_num - num
-- を作れば、
--
--   1  -> 2
--   3  -> 1
--   4  -> 3
--   7  -> 1
--   8  -> 1
--   9  -> 3
--   12 -> NULL
--
-- となり、
--   diff <> 1
-- の箇所が欠番区間の開始点になる。


-- ================================================
-- 図解: 次の1行を取得する
-- ================================================
--
--   並び順:
--   1 -> 3 -> 4 -> 7 -> 8 -> 9 -> 12
--
--   各行で見るフレーム:
--
--   現在 1   : [3]      -> next_num = 3
--   現在 3   : [4]      -> next_num = 4
--   現在 4   : [7]      -> next_num = 7
--   現在 7   : [8]      -> next_num = 8
--   現在 8   : [9]      -> next_num = 9
--   現在 9   : [12]     -> next_num = 12
--   現在 12  : [なし]   -> next_num = NULL
--
-- つまり、
--   各行ごとに「右隣の値」を持たせている。


-- ================================================
-- リスト8.17との関係
-- ================================================
--
-- リスト8.17では
--
--   next_num - num = diff
--
-- を計算していた。
--
-- その diff を使って
--   diff = 1 なら連続
--   diff > 1 なら欠番あり
-- と判定していた。
--
-- 今回のリスト8.18は、
--   その diff の元になっている
--   next_num の取得だけ
-- を切り出したものである。
--
-- つまり
--
--   リスト8.18:
--     各行の次の実在値を求める
--
--   リスト8.17:
--     次の実在値との差から欠番区間を求める
--
-- という関係になっている。
--
-- 今回は「1行あとを見る」処理の意味そのものを
-- 理解することが重要である。


-- ================================================
-- このSQLの本質
-- ================================================
--
-- このSQLの本質は、
--   自己結合を使わなくても、
--   ウィンドウ関数により
--   「ソート順で次に現れる値」
--   を直接取り出せるところにある。
--
-- つまり
--   隣接行比較の準備
-- を非常にコンパクトに書ける。
--
-- 欠番検出だけでなく、
--   前の行との比較
--   次の行との差分
--   境界点の検出
-- などでも同じ考え方が使える。
--
-- これがこのSQLの核心である。


-- ================================================
-- 構文ごとの意味
-- ================================================
--
-- ORDER BY num
--   → num 昇順で隣接関係を定義する
--
-- ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING
--   → 現在行のちょうど1行あとだけをフレームにする
--
-- MAX(num) OVER (...)
--   → その1行の num を取り出す
--
-- AS next_num
--   → 次の実在値として返す
-- ================================================