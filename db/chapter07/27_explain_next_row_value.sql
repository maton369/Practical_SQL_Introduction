-- 役割:
--   リスト8.18「サブクエリの中身」について、
--   MySQL の実行計画を確認する。
--
-- このSQLの目的:
--   DBMS が
--     ORDER BY num に基づくウィンドウ関数計算
--     次の1行の取得
--     next_num 付き中間結果の生成
--   をどう処理するかを見ること。
--
-- 学習上の主題:
--   - ウィンドウ関数による隣接行参照の EXPLAIN の見方
--   - ORDER BY に伴う filesort の意味
--   - index 走査とソート処理の関係
--
-- 今回の最重要ポイント:
--   このSQLは
--     num 昇順という順序
--   に依存して、
--     次の1行
--   を参照している。
--
--   そのため実行計画では
--     Using index
--     Using filesort
--   が見える可能性がある。
--
--   重要なのは、
--   このクエリが
--     単なる一覧取得ではなく、
--     ソート順に依存した隣接行参照
--   を行っている点である。
-- ================================================

EXPLAIN
SELECT
       num,
       MAX(num) OVER (
           ORDER BY num
           ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING
       ) AS next_num
  FROM Numbers;

-- ================================================
-- 実行計画で見たいポイント
-- ================================================
--
-- 1. Numbers の読み方
--    -> PRIMARY キー index を使って読めているか
--
-- 2. Using index
--    -> 必要列が num だけなので、
--       インデックスだけで足りる可能性がある
--
-- 3. Using filesort
--    -> ウィンドウ関数が ORDER BY num に依存して
--       次の1行を参照するため、
--       順序処理が必要になる可能性がある
--
-- 4. リスト8.17との関係
--    -> 8.18 は 8.17 の内側で使っていた
--       next_num 取得処理そのもの
--
--    つまり実行計画を見ることで、
--    欠番検出の前段階で何をしているかが分かる
-- ================================================