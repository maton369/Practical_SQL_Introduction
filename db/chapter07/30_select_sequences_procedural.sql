-- ================================================
-- ファイル名: 30_select_sequences_procedural.sql
-- 役割:
--   Numbers テーブルに存在する連続区間（シーケンス）を、
--   手続き型の考え方で求める。
--
-- このSQLの目的:
--   各 num に対して
--     1つ前の値との差
--     1つ後の値との差
--   を見て、
--   どこが連続区間の開始点か、
--   どこが連続区間の終了点か
--   を判定し、
--   最後に開始点 low と終了点 high を対応付けて
--   連続区間として返すこと。
--
-- 学習上の主題:
--   - 前行・次行との差分で境界を見つける方法
--   - ROW_NUMBER() による順序位置の固定
--   - NULL を含む列を後方に伝播させて区間終点を埋める方法
--   - 多段サブクエリで手続き的処理を段階分解する考え方
--
-- 今回の最重要ポイント:
--   このSQLはかなり手続き的であり、
--   大きく3段階で考えると理解しやすい。
--
--   1. TMP1:
--      各 num に対して
--        - 直前値との差 prev_diff
--        - 直後値との差 next_diff
--        - 並び順 seq
--      を求める
--
--   2. TMP2:
--      prev_diff を見て
--        「ここが区間開始か」
--      を判定し low を立てる。
--      next_diff を見て
--        「ここが区間終了か」
--      を判定し high を立てる。
--
--   3. TMP3:
--      low は開始点の行にしか入っていない。
--      high も終了点の行にしか入っていない。
--      そこで、low が立った行から先を見て
--      最初に出てくる high を拾い、
--      開始点と終了点を対応付ける。
--
--   つまりアルゴリズムとしては
--     「隣接差分で境界を見つける」
--       ->
--     「開始点と終了点をマーキングする」
--       ->
--     「開始点から見て対応する終了点を補完する」
--   という流れになっている。
--
--   これがこの手続き型シーケンス抽出の本質である。
-- ================================================

SELECT
       low,
       -- low:
       --   連続区間の開始値である。
       --
       --   TMP2 の段階で
       --     「ここが新しい連続区間の先頭である」
       --   と判定された行だけに値が入り、
       --   それ以外の行は NULL になる。
       --
       --   最後の WHERE low IS NOT NULL により、
       --   区間開始行だけを結果として返す。

       high
       -- high:
       --   連続区間の終了値である。
       --
       --   TMP2 の段階では
       --     「ここが区間末尾である」
       --   と判定された行だけに値が入る。
       --
       --   しかし開始点 low がある行と終了点 high がある行は
       --   一致しないことが多い。
       --
       --   そのため TMP3 で
       --     low がある行から先を見て、
       --     最初に出てくる high
       --   を補完している。
       --
       --   これにより、
       --   開始点と対応する終了点が1行にそろう。

  FROM
       (
           SELECT
                  low,
                  -- low:
                  --   TMP2 で作られた開始点列である。
                  --
                  --   開始点の行だけ num が入り、
                  --   それ以外は NULL である。

                  CASE
                      WHEN high IS NULL
                      THEN MIN(high) OVER (
                               ORDER BY seq
                               ROWS BETWEEN CURRENT ROW
                                        AND UNBOUNDED FOLLOWING
                           )
                      ELSE high
                  END AS high
                  -- CASE WHEN high IS NULL THEN ... ELSE high END:
                  --   ここが開始点と終了点を対応付ける処理である。
                  --
                  -- 背景:
                  --   TMP2 の時点では、
                  --     low は区間開始行にだけある
                  --     high は区間終了行にだけある
                  --   ため、
                  --   1つの行に両方そろっていない。
                  --
                  --   たとえば 7,8,9 が連続区間なら、
                  --   TMP2 のイメージは次のようになる。
                  --
                  --     num=7 -> low=7, high=NULL
                  --     num=8 -> low=NULL, high=NULL
                  --     num=9 -> low=NULL, high=9
                  --
                  --   ここで結果としては
                  --     low=7, high=9
                  --   を同じ行で持ちたい。
                  --
                  -- WHEN high IS NULL:
                  --   現在行に high が無いときは、
                  --   この行以降の範囲で
                  --   最初に見つかる high を探す。
                  --
                  -- MIN(high) OVER (
                  --     ORDER BY seq
                  --     ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING
                  -- ):
                  --   現在行から末尾までのフレームを見て、
                  --   その範囲に存在する high の最小値を取る。
                  --
                  --   ここで重要なのは、
                  --   high に入る値は「区間の終点」だけであり、
                  --   しかも seq 昇順では、現在の開始点に対応する終点が
                  --   もっとも近い将来側にあることである。
                  --
                  --   したがって
                  --     現在行以降の high の最小値
                  --   を取ると、
                  --   対応する終了点を拾える。
                  --
                  -- ELSE high:
                  --   もし現在行自身がすでに終了点なら、
                  --   その値をそのまま使う。
                  --
                  -- 結果:
                  --   low が立った行に、
                  --   対応する high が補完される。

             FROM
                  (
                      SELECT
                             CASE
                                 WHEN COALESCE(prev_diff, 0) <> 1
                                 THEN num
                                 ELSE NULL
                             END AS low,
                             -- low:
                             --   区間開始点を表す列である。
                             --
                             -- prev_diff:
                             --   現在値と1つ前の値との差である。
                             --
                             -- COALESCE(prev_diff, 0) <> 1:
                             --   前との差が 1 でなければ、
                             --   現在値は新しい連続区間の開始点である。
                             --
                             -- なぜか:
                             --   連続区間の途中なら、
                             --   直前の値との差は必ず 1 になる。
                             --
                             --   逆に
                             --     差が 1 でない
                             --   ということは、
                             --   前の値と連続していないので、
                             --   ここから新しい区間が始まる。
                             --
                             -- COALESCE(prev_diff, 0):
                             --   先頭行は前の行が存在しないため prev_diff は NULL になる。
                             --   その場合も開始点としたいので、
                             --   NULL を 0 に変換して
                             --   「1ではない」と判定している。
                             --
                             -- たとえば Numbers が
                             --   1,3,4,7,8,9,12
                             --   のとき、
                             --
                             --   1  は先頭なので開始点
                             --   3  は前が 1 で差が 2 なので開始点
                             --   4  は前が 3 で差が 1 なので開始点ではない
                             --   7  は前が 4 で差が 3 なので開始点
                             --   ...
                             --
                             --   となる。
                             --
                             --   したがって low には
                             --     1, 3, 7, 12
                             --   が入る。

                             CASE
                                 WHEN COALESCE(next_diff, 0) <> 1
                                 THEN num
                                 ELSE NULL
                             END AS high,
                             -- high:
                             --   区間終了点を表す列である。
                             --
                             -- next_diff:
                             --   次の値と現在値との差である。
                             --
                             -- COALESCE(next_diff, 0) <> 1:
                             --   次との差が 1 でなければ、
                             --   現在値は連続区間の終了点である。
                             --
                             -- なぜか:
                             --   連続区間の途中なら、
                             --   次の値との差は必ず 1 になる。
                             --
                             --   逆に
                             --     差が 1 でない
                             --   ということは、
                             --   次の値と連続していないので、
                             --   ここで区間が終わる。
                             --
                             -- COALESCE(next_diff, 0):
                             --   末尾行は次の行が無いため next_diff は NULL になる。
                             --   その場合も区間終了点としたいので、
                             --   NULL を 0 に変換して
                             --   「1ではない」と判定している。
                             --
                             -- たとえば Numbers が
                             --   1,3,4,7,8,9,12
                             --   のとき、
                             --
                             --   1  は次が 3 で差が 2 なので終了点
                             --   3  は次が 4 で差が 1 なので終了点ではない
                             --   4  は次が 7 で差が 3 なので終了点
                             --   7  は次が 8 で差が 1 なので終了点ではない
                             --   8  は次が 9 で差が 1 なので終了点ではない
                             --   9  は次が 12 で差が 3 なので終了点
                             --   12 は末尾なので終了点
                             --
                             --   となる。
                             --
                             --   したがって high には
                             --     1, 4, 9, 12
                             --   が入る。

                             seq
                             -- seq:
                             --   num 昇順の連番である。
                             --
                             --   TMP3 で
                             --     現在行から先へ向かって high を探す
                             --   ときの順序基準になる。
                             --
                             --   つまり seq は
                             --     データ列の手続き的な走査順
                             --   を固定するための列である。

                        FROM
                             (
                                 SELECT
                                        num,
                                        -- num:
                                        --   現在の実在値である。
                                        --
                                        --   この段階では各 num に対して、
                                        --   前後との差分と行順を付与する。

                                        MAX(num) OVER (
                                            ORDER BY num
                                            ROWS BETWEEN 1 FOLLOWING
                                                     AND 1 FOLLOWING
                                        ) - num AS next_diff,
                                        -- next_diff:
                                        --   次の実在値 - 現在値 を表す。
                                        --
                                        --   「1行あと」の num を取り、
                                        --   現在値との差分を計算している。
                                        --
                                        --   たとえば
                                        --     4 の次が 7 なら next_diff = 3
                                        --   となる。
                                        --
                                        --   これが 1 なら連続、
                                        --   1 でなければそこで区間が切れる。
                                        --
                                        -- MAX(num) OVER (
                                        --   ORDER BY num
                                        --   ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING
                                        -- ):
                                        --   ちょうど次の1行だけをフレームにしているので、
                                        --   実質的に「次の num を取る」意味になる。

                                        num - MAX(num) OVER (
                                                  ORDER BY num
                                                  ROWS BETWEEN 1 PRECEDING
                                                           AND 1 PRECEDING
                                              ) AS prev_diff,
                                        -- prev_diff:
                                        --   現在値 - 直前の実在値 を表す。
                                        --
                                        --   「1行前」の num を取り、
                                        --   現在値との差分を計算している。
                                        --
                                        --   たとえば
                                        --     7 の前が 4 なら prev_diff = 3
                                        --   となる。
                                        --
                                        --   これが 1 なら直前と連続、
                                        --   1 でなければ新区間の開始である。
                                        --
                                        -- MAX(num) OVER (
                                        --   ORDER BY num
                                        --   ROWS BETWEEN 1 PRECEDING AND 1 PRECEDING
                                        -- ):
                                        --   ちょうど前の1行だけをフレームにしているので、
                                        --   実質的に「前の num を取る」意味になる。

                                        ROW_NUMBER() OVER (ORDER BY num) AS seq
                                        -- seq:
                                        --   num 昇順の位置番号である。
                                        --
                                        --   1,2,3,... と各行に振られる。
                                        --
                                        --   TMP3 で「現在行から未来方向に向かって high を探す」
                                        --   処理の順序基準になる。
                                   FROM Numbers
                                   -- Numbers:
                                   --   元表である。
                                   --
                                   --   この段階では各 num に対して
                                   --     next_diff
                                   --     prev_diff
                                   --     seq
                                   --   を付けた TMP1 を作る。
                             ) TMP1
                             -- TMP1:
                             --   各 num の前後差分と順序番号を持つ派生表である。
                             --
                             --   たとえばデータ
                             --     1,3,4,7,8,9,12
                             --   に対しては概念的に
                             --
                             --   num  prev_diff next_diff seq
                             --   --------------------------------
                             --    1    NULL       2       1
                             --    3      2        1       2
                             --    4      1        3       3
                             --    7      3        1       4
                             --    8      1        1       5
                             --    9      1        3       6
                             --   12      3      NULL      7
                             --
                             --   のようになる。
                  ) TMP2
                  -- TMP2:
                  --   TMP1 の差分を使って
                  --     low 列
                  --     high 列
                  --   を立てた派生表である。
                  --
                  --   概念的には
                  --
                  --   low   high   seq
                  --   ----------------
                  --    1      1     1
                  --    3     NULL   2
                  --   NULL     4     3
                  --    7     NULL   4
                  --   NULL   NULL    5
                  --   NULL     9     6
                  --   12      12     7
                  --
                  --   のような形になる。
                  --
                  --   開始点は low にだけ、
                  --   終了点は high にだけ立っている。
       ) TMP3
       -- TMP3:
       --   low と対応する high を同じ行にそろえた派生表である。
       --
       --   この段階でようやく
       --     low ～ high
       -- をそのまま返せる形になる。

 WHERE low IS NOT NULL;
 -- WHERE low IS NOT NULL:
 --   区間開始行だけを最終結果として残す条件である。
 --
 --   TMP3 では high が補完された後も、
 --   開始点でない行には low が NULL のままである。
 --
 --   したがって
 --     low が立っている行だけを取れば、
 --     各連続区間につき1行
 --   の結果になる。
 --
 --   たとえば最終結果は
 --     1  ～ 1
 --     3  ～ 4
 --     7  ～ 9
 --     12 ～ 12
 --   となる。


-- ================================================
-- このSQLの処理の流れ
-- ================================================
--
-- 1. num 昇順で並べ、各行の前後差分と seq を求める
-- 2. prev_diff を見て開始点 low を立てる
-- 3. next_diff を見て終了点 high を立てる
-- 4. 各開始点の行から先を見て、最初に現れる終了点 high を補完する
-- 5. low がある行だけを結果として返す
--
-- 概念的には次のような処理に近い。
--
--   sort nums ascending
--
--   for each num:
--       prev_diff = current - previous
--       next_diff = next - current
--
--       if prev_diff != 1:
--           mark low = current
--
--       if next_diff != 1:
--           mark high = current
--
--   for each row with low:
--       fill corresponding high by looking forward
--
--   output rows where low exists
--
-- つまりこれは、
--   「前後差分で境界を見つけ、開始点に対応する終了点を結び付ける」
--   手続き型アルゴリズムである。


-- ================================================
-- 実データでのイメージ
-- ================================================
--
-- Numbers:
--   1
--   3
--   4
--   7
--   8
--   9
--   12
--
-- TMP1（前後差分）:
--
--   num  prev_diff next_diff seq
--   ----------------------------
--    1    NULL       2       1
--    3      2        1       2
--    4      1        3       3
--    7      3        1       4
--    8      1        1       5
--    9      1        3       6
--   12      3      NULL      7
--
-- TMP2（開始点/終了点の印）:
--
--   low   high   seq
--   ----------------
--    1      1     1
--    3     NULL   2
--   NULL     4     3
--    7     NULL   4
--   NULL   NULL    5
--   NULL     9     6
--   12      12     7
--
-- TMP3（開始点に終了点を補完）:
--
--   low   high
--   ----------
--    1      1
--    3      4
--   NULL    4
--    7      9
--   NULL    9
--   NULL    9
--   12     12
--
-- 最後に low IS NOT NULL を残すと
--
--    1  ～ 1
--    3  ～ 4
--    7  ～ 9
--   12  ～ 12
--
-- となる。
--
-- これが存在する連続シーケンスである。


-- ================================================
-- 図解: 境界を見つけて区間にする
-- ================================================
--
--   実在値:
--   1   3 4   7 8 9   12
--
--   prev_diff を見る -> 開始点を立てる
--   next_diff を見る -> 終了点を立てる
--
--   開始点:
--   1   3     7       12
--
--   終了点:
--   1     4     9     12
--
--   これを前から対応付ける:
--
--   1  -> 1
--   3  -> 4
--   7  -> 9
--   12 -> 12
--
--   よって
--
--   1  ～ 1
--   3  ～ 4
--   7  ～ 9
--   12 ～ 12
--
-- となる。


-- ================================================
-- リスト8.19との違い
-- ================================================
--
-- リスト8.19 は集合指向型であり、
--   rank - num が一定
-- という不変量を使って連続区間をグループ化していた。
--
-- 一方このリスト8.20は手続き型であり、
--   直前との差
--   直後との差
-- を見て
--   ここが開始点
--   ここが終了点
-- を明示的に決めている。
--
-- つまり
--
--   リスト8.19:
--     連続区間全体を同じ識別子 gp でまとめる
--
--   リスト8.20:
--     境界点を見つけ、その境界どうしをつなぐ
--
-- という違いがある。
--
-- 前者は不変量グループ化型、
-- 後者は境界検出・対応付け型である。
--
-- 結果は同じでも、
--   アルゴリズムの見え方はかなり異なる。
--
-- 今回は特に
--   「連続区間は、開始点と終了点で表現できる」
-- という手続き的な見方が重要である。


-- ================================================
-- このSQLの本質
-- ================================================
--
-- このSQLの本質は、
--   連続区間を
--     開始点
--     終了点
--   という境界情報に分解して表現しているところにある。
--
-- 連続区間そのものを直接グループ化するのではなく、
--   まず境界を検出し、
--   その境界を対応付けることで区間を作る。
--
-- これはかなり手続き的であり、
--   左から順番に走査しながら
--   「始まり」と「終わり」を意識する
-- 発想に近い。
--
-- そのため、
--   どこで区間が始まるか
--   どこで区間が終わるか
-- を丁寧に追いたいときに理解しやすい。
--
-- これがこのSQLの核心である。


-- ================================================
-- 構文ごとの意味
-- ================================================
--
-- next_diff
--   → 次の値との差。区間終了判定に使う
--
-- prev_diff
--   → 前の値との差。区間開始判定に使う
--
-- CASE WHEN COALESCE(prev_diff,0) <> 1 THEN num
--   → 開始点 low を立てる
--
-- CASE WHEN COALESCE(next_diff,0) <> 1 THEN num
--   → 終了点 high を立てる
--
-- MIN(high) OVER (
--   ORDER BY seq
--   ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING
-- )
--   → 現在行以降で最初に対応する終了点を補完する
--
-- WHERE low IS NOT NULL
--   → 区間開始行だけを最終結果として返す
-- ================================================