-- ファイル名: 25_explain_gap_ranges_next_row_compare.sql
-- 役割:
--   リスト8.17「1行あと」との比較版について、
--   MySQL の実行計画を確認する。
--
-- このSQLの目的:
--   DBMS が
--     ORDER BY num に基づくウィンドウ関数計算
--     次行値の取得
--     diff の生成
--     diff <> 1 による絞り込み
--   をどう処理するかを見ること。
--
-- 学習上の主題:
--   - ウィンドウ関数を用いた隣接行比較の EXPLAIN の見方
--   - 派生表 TMP の生成
--   - ソートや temporary の発生可能性
--   - 自己結合版との構造比較
--
-- 今回の最重要ポイント:
--   このSQLは
--     num 昇順に並んだ順序
--   に依存して、
--     次の1行
--   を参照している。
--
--   そのため実行計画では、
--     DERIVED
--     Using filesort
--     Using temporary
--   など、
--   ウィンドウ関数のための順序処理が見える可能性がある。
--
--   重要なのは、
--   このSQLが
--     先に diff 付き中間表を作る
--     その後で diff <> 1 を適用する
--   という二段構造である点である。
-- ================================================

EXPLAIN
SELECT
       num + 1 AS gap_start,
       '～',
       num + diff - 1 AS gap_end
  FROM
       (
           SELECT
                  num,
                  MAX(num) OVER (
                      ORDER BY num
                      ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING
                  ) - num AS diff
             FROM Numbers
       ) AS TMP
 WHERE diff <> 1;

-- ================================================
-- 実行計画で見たいポイント
-- ================================================
--
-- 1. 派生表 TMP の生成
--    -> まず各行に diff を付けた中間表を作る構造なので、
--       DERIVED が見えやすい
--
-- 2. ORDER BY num に基づくウィンドウ関数処理
--    -> 次の1行を取るには順序が必要なので、
--       filesort が出る可能性がある
--
-- 3. 外側の WHERE diff <> 1
--    -> 欠番がある箇所だけを残すフィルタ
--
-- 4. 自己結合版との比較
--    -> 8.16 は自己結合 + MIN で次の実在値を求めた
--    -> 8.17 はウィンドウ関数で次の1行を直接取る
--
--    つまり
--      候補全探索型
--    と
--      隣接参照型
--    の違いが実行計画にどう表れるかを見るのが重要である。
