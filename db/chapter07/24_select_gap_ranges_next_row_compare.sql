-- ================================================
-- このSQLの本質
-- ================================================
--
-- このSQLの本質は、
--   欠番区間を
--     「隣接する実在値の差分」
--   として表現しているところにある。
--
-- 自己結合版では
--   次の実在値を探すために
--   すべての上側候補を見る必要があった。
--
-- しかしこのSQLでは、
--   ソート済み順序の
--   ちょうど1行あと
-- を直接取得できる。
--
-- そのため、
--   欠番の有無は
--     diff = 次の実在値 - 現在値
--   だけで分かる。
--
--   diff = 1 なら連続
--   diff > 1 なら欠番あり
--
-- という非常に明快な形になる。
--
-- これがこの方法の核心である。


-- ================================================
-- 構文ごとの意味
-- ================================================
--
-- MAX(num) OVER (
--   ORDER BY num
--   ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING
-- )
--   → 次の1行の num を取り出す
--
-- ... - num AS diff
--   → 次の実在値との差分を求める
--
-- WHERE diff <> 1
--   → 連続していない箇所だけを残す
--
-- num + 1 AS gap_start
--   → 欠番区間の開始
--
-- num + diff - 1 AS gap_end
--   → 欠番区間の終了
-- ================================================