-- ================================================
-- ファイル名: 24_select_gap_ranges_next_row_compare.sql
-- 役割:
--   Numbers テーブルから、次の1行との比較により
--   欠番のかたまりを区間として表示する。
--
-- このSQLの目的:
--   各 num に対して
--     「次に現れる num」
--   をウィンドウ関数で取得し、
--   その差分から欠番区間
--     gap_start ～ gap_end
--   を求めること。
--
-- 学習上の主題:
--   - 「1行あと」の値をウィンドウ関数で取得する方法
--   - ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING の意味
--   - 差分 diff を使った欠番区間の計算
--   - 自己結合版との発想の違い
--
-- 今回の最重要ポイント:
--   このSQLでは、
--   まず各行 num に対して
--     直後の行の値
--   を取り出す。
--
--   その値から現在値 num を引くと、
--     diff = 次の実在値 - 現在値
--   が得られる。
--
--   もし diff = 1 なら、
--   現在値の直後に次の実在値が来ているので、
--   欠番は存在しない。
--
--   一方で diff > 1 なら、
--   その間に欠番のかたまりがある。
--
--   その区間は
--     gap_start = num + 1
--     gap_end   = num + diff - 1
--   で求められる。
--
--   つまりアルゴリズムとしては
--     1. 各行に対して次の行の値を取る
--     2. 現在値との差 diff を計算する
--     3. diff が 1 でない行だけを残す
--     4. 差分から欠番区間を作る
--   という「隣接行比較型」の欠番検出になっている。
--
--   これがこのSQLの本質である。
-- ================================================

SELECT
       num + 1 AS gap_start,
       -- gap_start:
       --   欠番区間の開始値である。
       --
       --   現在値 num の直後から、
       --   欠番が始まる可能性がある。
       --
       --   たとえば num=4 で、
       --   次の実在値が 7 なら、
       --   欠番は 5 から始まる。
       --
       --   したがって
       --     gap_start = num + 1
       --   となる。

       '～',
       -- 区切り文字:
       --   開始値と終了値の間を見やすく表示するための文字列である。
       --
       --   SQL のロジックには関与せず、
       --   表示用の補助列である。

       num + diff - 1 AS gap_end
       -- gap_end:
       --   欠番区間の終了値である。
       --
       --   diff は
       --     次の実在値 - 現在値
       --   を表す。
       --
       --   次の実在値が
       --     current + diff
       --   なので、
       --   欠番はその直前
       --     current + diff - 1
       --   まで続く。
       --
       --   たとえば
       --     num = 4
       --     次の実在値 = 7
       --   なら
       --     diff = 3
       --     gap_end = 4 + 3 - 1 = 6
       --   となり、
       --   欠番区間は 5～6 になる。

  FROM
       (
           SELECT
                  num,
                  -- num:
                  --   現在見ている実在値である。
                  --
                  --   この行を基準に、
                  --   直後の実在値との間に欠番があるかどうかを見る。

                  MAX(num) OVER (
                      ORDER BY num
                      ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING
                  ) - num AS diff
                  -- MAX(num) OVER (...):
                  --   ウィンドウ関数を使って、
                  --   「現在行の1行あと」の num を取り出している。
                  --
                  -- ORDER BY num:
                  --   num 昇順に並べた順序で行を見ている。
                  --
                  --   したがって
                  --     1
                  --     3
                  --     4
                  --     7
                  --     8
                  --     9
                  --     12
                  --   のような順序で隣接比較することになる。
                  --
                  -- ROWS BETWEEN 1 FOLLOWING AND 1 FOLLOWING:
                  --   ここが最重要ポイントである。
                  --
                  --   「現在行の1行あと、ちょうど1行だけ」
                  --   をウィンドウフレームとして指定している。
                  --
                  --   つまりこのフレームは、
                  --   今の行そのものではなく
                  --   次の行だけを対象にしている。
                  --
                  --   そのため MAX(num) と書いてはいるが、
                  --   実際には
                  --     次の1行の num
                  --   をそのまま取り出しているのと同じ意味になる。
                  --
                  --   たとえば現在行が 4 なら、
                  --   次の1行は 7 なので、
                  --   このウィンドウ関数の結果は 7 になる。
                  --
                  -- なぜ MAX を使うのか:
                  --   フレームが1行だけなので、
                  --   MAX を取ってもその1値自身が返る。
                  --
                  --   したがって
                  --     次行取得
                  --   のような役割で使える。
                  --
                  -- - num:
                  --   現在値との差を取ることで
                  --     diff = 次の実在値 - 現在値
                  --   を得ている。
                  --
                  -- diff の意味:
                  --   たとえば
                  --     1 の次が 3 なら diff=2
                  --     3 の次が 4 なら diff=1
                  --     4 の次が 7 なら diff=3
                  --   になる。
                  --
                  --   ここで
                  --     diff = 1
                  --   なら連続している。
                  --
                  --   diff > 1
                  --   ならその間に欠番が存在する。
             FROM Numbers
             -- Numbers:
             --   元表である。
             --
             --   ここでは各行に対して
             --     直後の実在値との差 diff
             --   を付けた中間表を作っている。
       ) AS TMP
       -- TMP:
       --   各実在値 num と、
       --   次の実在値との差 diff を持つ派生表である。
       --
       --   外側クエリではこの diff を見て、
       --   欠番がある行だけを残す。

 WHERE diff <> 1;
 -- WHERE diff <> 1:
 --   隣接差が 1 ではない行だけを残す。
 --
 --   diff = 1 の場合:
 --     現在値の次に、ちょうど連続する値が存在する。
 --     つまり欠番は無い。
 --
 --   diff > 1 の場合:
 --     その間に 1つ以上の欠番がある。
 --
 -- たとえば
 --   1 -> 次は 3   -> diff=2 -> 欠番あり
 --   3 -> 次は 4   -> diff=1 -> 欠番なし
 --   4 -> 次は 7   -> diff=3 -> 欠番あり
 --
 -- という意味である。
 --
 -- 注意:
 --   最後の行には「次の行」が存在しないため、
 --   diff は NULL になる可能性がある。
 --
 --   SQL の三値論理では
 --     NULL <> 1
 --   は真ではなく UNKNOWN になるため、
 --   最後の行は結果に出ない。
 --
 --   これは「最後の実在値の後ろ側の無限の欠番」を
 --   今回は扱わないという意味でも自然である。


-- ================================================
-- このSQLの処理の流れ
-- ================================================
--
-- 1. Numbers を num 昇順で並べる
-- 2. 各行について、次の1行の num を取る
-- 3. 現在値との差 diff を計算する
-- 4. diff が 1 でない行だけを残す
-- 5. gap_start = num + 1
--    gap_end   = num + diff - 1
--    を返す
--
-- 概念的には次のような処理に近い。
--
--   sort nums ascending
--
--   for each row i:
--       next_num = value at row i+1
--       diff = next_num - current_num
--
--       if diff != 1:
--           output (current_num + 1) ~ (next_num - 1)
--
-- つまりこれは、
--   「隣り合う実在値どうしの差分から欠番区間を作る」
--   アルゴリズムである。


-- ================================================
-- 実データでのイメージ
-- ================================================
--
-- Numbers:
--   1
--   3
--   4
--   7
--   8
--   9
--   12
--
-- 各行について、次の1行との差 diff を見る。
--
-- 現在 1:
--   次は 3
--   diff = 3 - 1 = 2
--   diff <> 1 なので欠番あり
--   gap = 2 ～ 2
--
-- 現在 3:
--   次は 4
--   diff = 1
--   -> 欠番なし
--
-- 現在 4:
--   次は 7
--   diff = 3
--   -> 欠番あり
--   gap = 5 ～ 6
--
-- 現在 7:
--   次は 8
--   diff = 1
--   -> 欠番なし
--
-- 現在 8:
--   次は 9
--   diff = 1
--   -> 欠番なし
--
-- 現在 9:
--   次は 12
--   diff = 3
--   -> 欠番あり
--   gap = 10 ～ 11
--
-- 現在 12:
--   次行なし
--   diff = NULL
--   -> 結果に出ない
--
-- よって最終結果は概ね
--
--   2   ～   2
--   5   ～   6
--   10  ～   11
--
-- になる。


-- ================================================
-- 図解: 1行あととの比較
-- ================================================
--
--   実在値:
--   1   3 4   7 8 9   12
--   |   | |   | | |    |
--   |   | |   | | |    +-- 次行なし
--   |   | |   | | +------- diff=3 -> gap 10～11
--   |   | |   | +--------- diff=1 -> gap なし
--   |   | |   +----------- diff=1 -> gap なし
--   |   | +--------------- diff=3 -> gap 5～6
--   |   +----------------- diff=1 -> gap なし
--   +--------------------- diff=2 -> gap 2～2
--
-- つまり、
--   各行から次の行までの差を見て、
--   1 でなければその間を欠番区間として返している。


