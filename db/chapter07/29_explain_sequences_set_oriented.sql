--   MySQL の実行計画を確認する。
--
-- このSQLの目的:
--   DBMS が
--     自己結合
--     COUNT による rank 相当値の計算
--     gp の生成
--     gp ごとの GROUP BY
--   をどう処理するかを見ること。
--
-- 学習上の主題:
--   - 連続区間グループ化SQLの EXPLAIN の見方
--   - 自己結合による順位的情報生成
--   - 派生表 N の生成
--   - 外側の GROUP BY による区間化
--
-- 今回の最重要ポイント:
--   このSQLは
--     1. 内側で各 num に gp を付ける
--     2. 外側で gp ごとに区間化する
--   という二段構造である。
--
--   そのため実行計画では
--     DERIVED
--     Using temporary
--     Using filesort
--   などが現れる可能性がある。
--
--   また、自己結合により
--     N1 以下の N2 を数える
--   構造がどう見えるかも重要である。
-- ================================================

EXPLAIN
SELECT
       MIN(num) AS low,
       '～',
       MAX(num) AS high
  FROM
       (
           SELECT
                  N1.num,
                  COUNT(N2.num) - N1.num AS gp
             FROM Numbers N1
                  INNER JOIN Numbers N2
                    ON N2.num <= N1.num
            GROUP BY N1.num
       ) AS N(num, gp)
 GROUP BY gp;

-- ================================================
-- 実行計画で見たいポイント
-- ================================================
--
-- 1. 内側の自己結合
--    -> N1.num ごとに N2.num <= N1.num を満たす件数を数える構造
--
-- 2. 派生表 N の生成
--    -> 各 num に gp を付けた中間表をまず作る
--
-- 3. 外側の GROUP BY gp
--    -> 同じ連続区間識別子を持つ行をまとめる
--
-- 4. Using temporary / Using filesort
--    -> GROUP BY が2段あるので、中間処理が現れる可能性がある
--
-- 5. リスト8.16/8.17との比較
--    -> 欠番区間を探すのではなく、
--       実在値の連続区間を直接グループ化している
