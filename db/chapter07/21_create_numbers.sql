-- ================================================
-- ファイル名: 21_create_numbers.sql
-- 役割:
--   整数を保持する Numbers テーブルを作成する。
--
-- このSQLの目的:
--   欠番の区間を調べるための、元となる整数集合を保持すること。
--
-- 学習上の主題:
--   - 連番の中で抜けている区間を見つける問題
--   - 自己結合を使って「次に大きい値」を探す考え方
--   - 集約 MIN() を使って直後の境界値を求める方法
--
-- 今回の最重要ポイント:
--   この表には
--     1, 3, 4, 7, 8, 9, 12
-- のように、一部が欠けた整数列が入る。
--
--   後続のSQLでは、
--   各数 N1.num に対して
--     「それより大きい数のうち最小のもの」
--   を探す。
--
--   その最小値が
--     N1.num + 1
--   より大きければ、
--   その間に欠番のかたまりが存在する。
--
--   つまりこの問題の本質は
--     「現在値の直後に来る実在値との間の空白」
--   を見つけることにある。
-- ================================================

CREATE TABLE Numbers
(
    num INTEGER PRIMARY KEY
    -- num:
    --   整数値を表す列である。
    --
    --   今回のテーブルは1列だけで構成され、
    --   この num 自体が主キーになっている。
    --
    --   主キーなので値は重複しない。
    --
    --   そのため、
    --   この列は
    --     整数集合そのもの
    --   を表していると見てよい。
    --
    --   後続の欠番検出SQLでは、
    --   この列を
    --     現在値
    --     次の実在値
    --   の両方として自己結合で使う。
);