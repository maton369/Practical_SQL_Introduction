-- ================================================
-- ファイル名: 28_select_sequences_set_oriented.sql
-- 役割:
--   Numbers テーブルに存在する連続区間（シーケンス）を、
--   集合指向的な考え方で求める。
--
-- このSQLの目的:
--   バラバラに見える整数集合の中から、
--   連続してつながっている値のかたまりを
--     low ～ high
-- の区間として取り出すこと。
--
-- 学習上の主題:
--   - 連続値のかたまりをグループ化する方法
--   - COUNT(*) と値そのものの差を使ったグループ識別子の作り方
--   - 自己結合 + GROUP BY による順位的な情報の抽出
--   - 欠番区間ではなく「存在する値の区間」を返す考え方
--
-- 今回の最重要ポイント:
--   このSQLの核心は、
--   各値 num に対して
--
--     COUNT(N2.num) - N1.num
--
--   という値を作っているところにある。
--
--   ここで
--     COUNT(N2.num)
--   は、
--   N1.num 以下に存在する数の個数であり、
--   いわば
--     「昇順に見たときの位置番号」
--   に相当する。
--
--   連続している値の並びでは、
--   num が 1 増えるたびに
--   COUNT も 1 増える。
--
--   したがって
--
--     COUNT(N2.num) - N1.num
--
--   は同じ値のまま保たれる。
--
--   逆に、欠番があると
--   num だけが飛んで増え、
--   COUNT の増加とズレるため、
--   この差の値が変化する。
--
--   つまりこの差は
--     「同じ連続区間に属しているかどうか」
--   を識別するグループ番号のように使える。
--
--   その差ごとに GROUP BY し、
--   MIN(num) と MAX(num) を取れば、
--   連続区間の始点と終点が得られる。
--
--   これがこの集合指向型シーケンス抽出の本質である。
-- ================================================

SELECT
       MIN(num) AS low,
       -- low:
       --   連続区間の開始値である。
       --
       --   内側サブクエリで作った gp
       --   （連続区間を識別する値）
       --   ごとにグループ化したうえで、
       --   その区間に属する最小の num を返している。
       --
       --   たとえば
       --     7,8,9
       -- の連続区間なら、
       --   low = 7
       -- になる。

       '～',
       -- 区切り文字:
       --   区間表示を見やすくするための文字列である。
       --
       --   SQLロジックには関与せず、
       --   low と high の間をつなぐ表示用の列である。

       MAX(num) AS high
       -- high:
       --   連続区間の終了値である。
       --
       --   gp ごとにまとめたグループの中で、
       --   最大の num を返している。
       --
       --   たとえば
       --     7,8,9
       -- の連続区間なら、
       --   high = 9
       -- になる。

  FROM
       (
           SELECT
                  N1.num,
                  -- N1.num:
                  --   現在見ている実在値である。
                  --
                  --   この値がどの連続区間に属するかを判定するために、
                  --   以降で gp を計算する。

                  COUNT(N2.num) - N1.num AS gp
                  -- COUNT(N2.num):
                  --   N1.num 以下の値が何個存在するかを表す。
                  --
                  --   自己結合条件
                  --     N2.num <= N1.num
                  -- により、
                  --   N1 より小さいか同じ値をすべて数えている。
                  --
                  --   たとえば Numbers が
                  --     1,3,4,7,8,9,12
                  -- のとき、
                  --
                  --   N1.num = 1 なら COUNT = 1
                  --   N1.num = 3 なら COUNT = 2
                  --   N1.num = 4 なら COUNT = 3
                  --   N1.num = 7 なら COUNT = 4
                  --   ...
                  --
                  --   となる。
                  --
                  --   これは「存在する値だけに対する順位」
                  --   と考えると分かりやすい。
                  --
                  -- COUNT(N2.num) - N1.num AS gp:
                  --   この差分が、連続区間の識別子になる。
                  --
                  --   連続区間の例:
                  --     7,8,9
                  -- に対して考えると、
                  --
                  --     num=7 -> COUNT=4 -> gp=4-7=-3
                  --     num=8 -> COUNT=5 -> gp=5-8=-3
                  --     num=9 -> COUNT=6 -> gp=6-9=-3
                  --
                  --   と、同じ値になる。
                  --
                  --   つまり連続している限り、
                  --   gp は一定である。
                  --
                  --   一方で欠番があると、
                  --   num は飛んで増えるのに
                  --   COUNT は 1 しか増えないので、
                  --   gp が変わる。
                  --
                  --   例:
                  --     num=4 -> COUNT=3 -> gp=-1
                  --     num=7 -> COUNT=4 -> gp=-3
                  --
                  --   4 と 7 の間には欠番 5,6 があるので、
                  --   gp が変化している。
                  --
                  --   この性質を利用して、
                  --   同じ gp を持つ行を
                  --   同じ連続区間に属するものとして扱う。

             FROM Numbers N1
                  INNER JOIN Numbers N2
                    ON N2.num <= N1.num
                    -- 自己結合:
                    --   同じ Numbers 表を
                    --     N1 = 現在値側
                    --     N2 = N1 以下の値を数える側
                    --   として2回使っている。
                    --
                    -- N2.num <= N1.num:
                    --   N1.num 以下の値をすべて集める条件である。
                    --
                    --   これにより、
                    --   N1 ごとに
                    --     「自分以下はいくつあるか」
                    --   を COUNT で求められる。
                    --
                    --   つまりここは、
                    --   各 num に対して順位的な情報を作るための自己結合である。

            GROUP BY N1.num
            -- GROUP BY N1.num:
            --   N1 の各値ごとに、
            --   それ以下の N2 の個数を集計する。
            --
            --   これによって各 num に対して
            --     gp = COUNT(N2.num) - N1.num
            --   が1つずつ決まる。
       ) AS N(num, gp)
       -- N:
       --   各 num と、その num が属する連続区間識別子 gp
       --   を持つ派生表である。
       --
       --   概念的には次のような形になる。
       --
       --   num   gp
       --   --------
       --    1    0
       --    3   -1
       --    4   -1
       --    7   -3
       --    8   -3
       --    9   -3
       --   12   -5
       --
       --   同じ gp の値どうしが、
       --   同じ連続区間に属する。

 GROUP BY gp;
 -- GROUP BY gp:
 --   同じ連続区間識別子を持つ行をまとめる。
 --
 --   すると、
 --   連続している値のかたまりごとに
 --   1グループになる。
 --
 --   そのグループに対して
 --     MIN(num)
 --     MAX(num)
 --   を取ることで、
 --   区間の始点と終点が得られる。


-- ================================================
-- このSQLの処理の流れ
-- ================================================
--
-- 1. 各 num について、自分以下の値の件数を数える
-- 2. gp = 件数 - num を計算する
-- 3. 同じ gp を持つ num を同じ連続区間とみなす
-- 4. gp ごとに MIN(num), MAX(num) を取る
-- 5. 連続区間 low ～ high を返す
--
-- 概念的には次のような処理に近い。
--
--   for each num in Numbers:
--       rank = count(values <= num)
--       gp = rank - num
--
--   group rows by gp
--
--   for each group:
--       output min(num) ~ max(num)
--
-- つまりこれは、
--   「順位と値のズレが一定なものを同じ連続区間とみなす」
--   集合指向型アルゴリズムである。


-- ================================================
-- 実データでのイメージ
-- ================================================
--
-- Numbers:
--   1
--   3
--   4
--   7
--   8
--   9
--   12
--
-- 各 num に対して
--   rank = count(values <= num)
--   gp = rank - num
-- を計算すると、
--
--   num=1   -> rank=1 -> gp= 0
--   num=3   -> rank=2 -> gp=-1
--   num=4   -> rank=3 -> gp=-1
--   num=7   -> rank=4 -> gp=-3
--   num=8   -> rank=5 -> gp=-3
--   num=9   -> rank=6 -> gp=-3
--   num=12  -> rank=7 -> gp=-5
--
-- となる。
--
-- これを gp ごとにまとめると、
--
--   gp= 0  -> {1}
--   gp=-1  -> {3,4}
--   gp=-3  -> {7,8,9}
--   gp=-5  -> {12}
--
-- となる。
--
-- したがって最終結果は概ね
--
--   1  ～ 1
--   3  ～ 4
--   7  ～ 9
--   12 ～ 12
--
-- になる。
--
-- これは Numbers の中に存在する
-- 連続シーケンスを正しく表している。


-- ================================================
-- 図解: 順位と値のズレが同じなら同じ連続区間
-- ================================================
--
--   num:   1   3   4   7   8   9   12
--   rank:  1   2   3   4   5   6    7
--   gp:    0  -1  -1  -3  -3  -3   -5
--
--   gp が同じものをまとめる:
--
--   0   -> 1
--   -1  -> 3,4
--   -3  -> 7,8,9
--   -5  -> 12
--
--   それぞれの MIN, MAX を取る:
--
--   1  ～ 1
--   3  ～ 4
--   7  ～ 9
--   12 ～ 12
--
-- つまり、
--   「連続している値では gp が一定」
-- という性質を使って区間を作っている。


-- ================================================
-- リスト8.16/8.17との違い
-- ================================================
--
-- リスト8.16 や 8.17 は
--   欠番区間
-- を返していた。
--
--   つまり
--     実在値どうしの間にある空白
--   を取り出していた。
--
-- 一方このリスト8.19は
--   実在する値の連続区間
-- を返している。
--
--   つまり
--     存在している値のかたまり
--   を直接まとめている。
--
-- また、アルゴリズムも違う。
--
--   8.16/8.17:
--     隣接する実在値との間の空白を見る
--
--   8.19:
--     各値に区間識別子 gp を付け、
--     同じ識別子ごとにまとめる
--
-- つまり
--   欠番検出型
-- と
--   連続区間グループ化型
-- の違いがある。


-- ================================================
-- このSQLの本質
-- ================================================
--
-- このSQLの本質は、
--   連続区間を
--     値の並びそのもの
--   ではなく、
--     rank - value の不変量
--   として表現しているところにある。
--
-- 連続している値では、
--   値が1増えるごとに順位も1増える。
--
-- そのため
--   rank - value
-- は一定になる。
--
-- 一方、欠番があると
--   value だけが飛んで増えるので、
--   この差が変わる。
--
-- つまり
--   連続性
-- を
--   差の一定性
--   として捉えている。
--
-- これがこの集合指向型シーケンス抽出の核心である。


-- ================================================
-- 構文ごとの意味
-- ================================================
--
-- N2.num <= N1.num
--   → N1 以下の値をすべて集める
--
-- COUNT(N2.num)
--   → N1 の順位に相当する件数を求める
--
-- COUNT(N2.num) - N1.num AS gp
--   → 連続区間識別子を作る
--
-- GROUP BY gp
--   → 同じ連続区間に属する値をまとめる
--
-- MIN(num) AS low
--   → 区間の開始値
--
-- MAX(num) AS high
--   → 区間の終了値
-- ================================================